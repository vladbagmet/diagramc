// Writes skills/uml/reference.md, the per-kind cheat sheet of the usage skill,
// from the kind registry and the JSON Schemas (what `uml kinds` and
// `uml schema <kind>` print), so it cannot drift from the code.
//   npm run build && node scripts/generate-skill-reference.mjs
// test/skill.test.mjs fails when the committed file differs from this output.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BIN, kindSummaries, schemaOf } from '../dist/commands.js';

export const REFERENCE_FILE = fileURLToPath(new URL(`../skills/${BIN}/reference.md`, import.meta.url));

/** The definition a `$ref` of the form `#/definitions/<name>` points to. */
function resolve(schema, node) {
  const ref = node?.$ref;
  if (typeof ref !== 'string') return node;
  const name = ref.replace('#/definitions/', '');
  return schema.definitions?.[name];
}

const code = value => `\`${value}\``;

/** `a`, `b` and `c` (or "none"). */
const list = values => (values.length === 0 ? 'none' : values.join(', '));

/** Required properties of an object schema, apart from `skip`. */
const required = (node, skip) => (node.required ?? []).filter(p => p !== skip);

/** One line per array property: its item types (and their required properties) or its item fields. */
function arrayLine(schema, property, node) {
  const items = resolve(schema, node.items);
  if (!items) return;
  const bounds = node.minItems ? `${node.minItems} to ${node.maxItems}` : `up to ${node.maxItems}`;
  const discriminator = items.discriminator?.propertyName;
  if (discriminator && Array.isArray(items.oneOf)) {
    const variants = items.oneOf.map(reference => {
      const variant = resolve(schema, reference);
      const type = variant.properties[discriminator];
      const needs = required(variant, discriminator);
      return `${list((type.enum ?? [type.const]).map(code))}${needs.length > 0 ? ` (${needs.join(', ')})` : ''}`;
    });
    return `- ${code(`${property}[].${discriminator}`)} (${bounds}): ${list(variants)}`;
  }
  if (items.properties) {
    const needs = new Set(items.required);
    const fields = Object.keys(items.properties).map(p => (needs.has(p) ? `${code(p)}*` : code(p)));
    return `- ${code(`${property}[]`)} (${bounds}): ${list(fields)}`;
  }
}

/** The whole reference as Markdown. */
export function skillReference() {
  const lines = [
    `# ${BIN} reference: every diagram kind`,
    '',
    `<!-- Generated by scripts/generate-skill-reference.mjs from \`${BIN} kinds\` and \`${BIN} schema <kind>\`; do not edit by hand. -->`,
    '',
    'One section per kind: what it draws, its backends (the first is the default),',
    'the text formats it exports to and imports from, its top-level properties',
    '(`*` marks required ones) and, for each list, the `type` values with the',
    `properties each one requires. \`${BIN} schema <kind>\` has every property with its`,
    `description; \`${BIN} example <kind>\` prints a minimal valid model.`,
  ];
  for (const summary of kindSummaries()) {
    const schema = schemaOf(summary.kind);
    const needs = new Set(schema.required);
    const properties = Object.keys(schema.properties).filter(p => p !== 'version');
    lines.push(
      '',
      `## ${summary.kind}`,
      '',
      `${summary.title}: ${summary.summary}`,
      '',
      `- Backends: ${list(summary.backends)}. Exports to: ${list(summary.exports)}. Imports from: ${list(summary.imports)}.`,
      `- Top level: ${list(properties.map(p => (needs.has(p) ? `${code(p)}*` : code(p))))}.`,
    );
    for (const property of properties) {
      const node = schema.properties[property];
      if (node.type !== 'array') continue;
      const line = arrayLine(schema, property, node);
      if (line) lines.push(line);
    }
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(REFERENCE_FILE, skillReference());
